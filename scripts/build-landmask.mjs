// Rasterises Natural Earth 110m land (world-atlas topojson) into a W×H bitmask
// for the ASCII globe. Run: node scripts/build-landmask.mjs path/to/land-110m.json
import fs from "node:fs";

const W = 192, H = 96;
const topo = JSON.parse(fs.readFileSync(process.argv[2], "utf8"));
const { scale, translate } = topo.transform;

const arcs = topo.arcs.map((arc) => {
  let x = 0, y = 0;
  return arc.map(([dx, dy]) => {
    x += dx; y += dy;
    return [x * scale[0] + translate[0], y * scale[1] + translate[1]];
  });
});
const ring = (ids) => ids.flatMap((id, k) => {
  const a = id < 0 ? [...arcs[~id]].reverse() : arcs[id];
  return k ? a.slice(1) : a;
});

const rings = [];
const walk = (g) => {
  if (g.type === "GeometryCollection") g.geometries.forEach(walk);
  else if (g.type === "Polygon") g.arcs.forEach((r) => rings.push(ring(r)));
  else if (g.type === "MultiPolygon") g.arcs.forEach((p) => p.forEach((r) => rings.push(ring(r))));
};
walk(topo.objects.land);

const inside = (lon, lat) => {
  let c = false;
  for (const r of rings) {
    for (let i = 0, j = r.length - 1; i < r.length; j = i++) {
      const [xi, yi] = r[i], [xj, yj] = r[j];
      if ((yi > lat) !== (yj > lat) && lon < ((xj - xi) * (lat - yi)) / (yj - yi) + xi) c = !c;
    }
  }
  return c;
};

const bytes = new Uint8Array((W * H) / 8);
let land = 0;
for (let y = 0; y < H; y++) {
  const lat = 90 - ((y + 0.5) / H) * 180;
  for (let x = 0; x < W; x++) {
    const lon = -180 + ((x + 0.5) / W) * 360;
    if (inside(lon, lat)) { const i = y * W + x; bytes[i >> 3] |= 1 << (i & 7); land++; }
  }
}
const b64 = Buffer.from(bytes).toString("base64");
fs.writeFileSync(
  "src/data/landmask.ts",
  `// Generated by scripts/build-landmask.mjs from Natural Earth 110m land (public domain).\nexport const LAND_W = ${W};\nexport const LAND_H = ${H};\nexport const LAND_BITS = "${b64}";\n`,
);
console.log(`land cells ${land}/${W * H} (${((100 * land) / (W * H)).toFixed(1)}%), ${b64.length} b64 chars`);
for (let y = 0; y < H; y += 4) { let s = ""; for (let x = 0; x < W; x += 2) { const i = y * W + x; s += bytes[i >> 3] & (1 << (i & 7)) ? "#" : "."; } console.log(s); }
